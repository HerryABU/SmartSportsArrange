#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""生成运动会多表导入烟测数据（含场地表）。

产出运动会导入数据.xlsx，Sheets 与后端 ExcelService 的模板/识别口径严格一致：
年级表 / 班级表 / 全名单表 / 场地表 / 运动项目表 / 报名表。
场地编码与运动项目表的「场地号」对应（TRACK/FIELD_A/FIELD_B/SWIM），
导入后场地管理页即不再是「暂无数据」。
"""
import os
import openpyxl

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "运动会导入数据.xlsx")

# 年级表：年级 / 序号
GRADES = [
    ("高一年级", "1"),
    ("高二年级", "2"),
]

# 班级表：班级名称 / 班级编码 / 年级 / 班主任
CLASSES = [
    ("高一1班", "G1-01", "高一年级", "张老师"),
    ("高二1班", "G2-01", "高二年级", "李老师"),
]

# 全名单表：年级 / 班级 / 姓名 / 学号 / 性别
ROSTER = [
    ("高一年级", "高一1班", "张三", "2024001", "男"),
    ("高一年级", "高一1班", "李四", "2024002", "女"),
    ("高二年级", "高二1班", "王五", "2023001", "男"),
]

# 场地表：场地编码 / 场地名称 / 类型 / 可容纳项目数 / 最大并行数 / 排序 / 启用
VENUES = [
    ("TRACK", "主跑道", "径赛", "1", "8", "1", "是"),
    ("FIELD_A", "田赛A区", "田赛", "6", "3", "2", "是"),
    ("FIELD_B", "田赛B区", "田赛", "4", "2", "3", "是"),
    ("SWIM", "游泳馆", "游泳", "8", "4", "4", "是"),
]

# 运动项目表：项目代码 / 项目名称 / 每组人数 / 每批组数 / 项目类型 / 场地号 / 每批所需时间(分)
EVENTS = [
    ("100M", "100米", "1", "6", "径赛", "TRACK", "20"),
    ("4X100M", "4×100米接力", "4", "8", "径赛", "TRACK", "30"),
    ("TY_LJ", "立定跳远", "1", "4", "田赛", "FIELD_A", "90"),
    ("SWIM50", "50米蛙泳", "1", "4", "游泳", "SWIM", "25"),
    ("TUG", "拔河", "15", "1", "趣味运动会", "FIELD_B", "300"),
]

# 报名表：年级 / 班级 / 姓名 / 学号 / 性别 / 项目 / 组号
SIGNUP = [
    ("高一年级", "高一1班", "张三", "2024001", "男", "100米", ""),
    ("高一年级", "高一1班", "张三", "2024001", "男", "4×100米接力", "A"),
    ("高一年级", "高一1班", "李四", "2024002", "女", "立定跳远", ""),
    ("高二年级", "高二1班", "王五", "2023001", "男", "拔河", "A"),
]


def add_sheet(wb, title, headers, rows):
    ws = wb.create_sheet(title)
    ws.append(list(headers))
    for r in rows:
        ws.append(list(r))
    return ws


def main():
    wb = openpyxl.Workbook()
    wb.remove(wb.active)  # 去掉默认空表

    add_sheet(wb, "年级表", ("年级", "序号"), GRADES)
    add_sheet(wb, "班级表", ("班级名称", "班级编码", "年级", "班主任"), CLASSES)
    add_sheet(wb, "全名单表", ("年级", "班级", "姓名", "学号", "性别"), ROSTER)
    add_sheet(wb, "场地表",
              ("场地编码", "场地名称", "类型", "可容纳项目数", "最大并行数", "排序", "启用"),
              VENUES)
    add_sheet(wb, "运动项目表",
              ("项目代码", "项目名称", "每组人数", "每批组数", "项目类型", "场地号", "每批所需时间(分)"),
              EVENTS)
    add_sheet(wb, "报名表",
              ("年级", "班级", "姓名", "学号", "性别", "项目", "组号"), SIGNUP)

    wb.save(OUT)
    print("已生成:", OUT)
    print("Sheets:", wb.sheetnames)
    print("场地数:", len(VENUES), "(TRACK 径赛 / FIELD_A 田赛 / FIELD_B 田赛 / SWIM 游泳)")
    print("场地编码需与运动项目表「场地号」一致：",
          {r[5] for r in EVENTS} <= {v[0] for v in VENUES})


if __name__ == "__main__":
    main()
